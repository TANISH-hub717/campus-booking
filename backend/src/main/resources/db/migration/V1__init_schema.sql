-- V1__init_schema.sql
-- Schema definition for College Venue Booking and Management System

CREATE TABLE app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    full_name VARCHAR(150) NOT NULL,
    staff_id VARCHAR(50) NOT NULL,
    department VARCHAR(150),
    designation VARCHAR(100),
    phone VARCHAR(20),
    role VARCHAR(30) NOT NULL DEFAULT 'ROLE_FACULTY',
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP
);

CREATE TABLE department_cell (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL UNIQUE,
    type VARCHAR(50) NOT NULL DEFAULT 'DEPARTMENT',
    description TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_by_user_id BIGINT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_dept_creator FOREIGN KEY (created_by_user_id) REFERENCES app_user(id) ON DELETE SET NULL
);

CREATE TABLE venue (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL UNIQUE,
    type VARCHAR(50) NOT NULL,
    building VARCHAR(100) NOT NULL,
    floor VARCHAR(50) NOT NULL,
    room_number VARCHAR(50),
    capacity INT NOT NULL CHECK (capacity > 0),
    description TEXT,
    equipment TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    booking_instructions TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP
);

CREATE TABLE booking (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_reference VARCHAR(30) NOT NULL UNIQUE,
    venue_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    department_cell_id BIGINT NOT NULL,
    title VARCHAR(200) NOT NULL,
    purpose TEXT,
    event_date DATE NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    attendees INT NOT NULL CHECK (attendees > 0),
    equipment_requirements TEXT,
    setup_requirements TEXT,
    additional_remarks TEXT,
    status VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    rejection_reason TEXT,
    approved_by_user_id BIGINT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP,
    CONSTRAINT fk_booking_venue FOREIGN KEY (venue_id) REFERENCES venue(id) ON DELETE RESTRICT,
    CONSTRAINT fk_booking_user FOREIGN KEY (user_id) REFERENCES app_user(id) ON DELETE RESTRICT,
    CONSTRAINT fk_booking_dept FOREIGN KEY (department_cell_id) REFERENCES department_cell(id) ON DELETE RESTRICT,
    CONSTRAINT fk_booking_approver FOREIGN KEY (approved_by_user_id) REFERENCES app_user(id) ON DELETE SET NULL,
    CONSTRAINT chk_booking_time_order CHECK (start_time < end_time)
);

CREATE INDEX idx_booking_venue_date_status ON booking(venue_id, event_date, status);
CREATE INDEX idx_booking_user ON booking(user_id);
CREATE INDEX idx_booking_dept ON booking(department_cell_id);
CREATE INDEX idx_venue_type_active ON venue(type, is_active);
CREATE INDEX idx_dept_active ON department_cell(is_active);
