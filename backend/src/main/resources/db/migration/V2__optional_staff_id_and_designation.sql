-- 1. Make staff_id optional for faculty registrations
ALTER TABLE app_user ALTER COLUMN staff_id DROP NOT NULL;

-- 2. Create dynamic designation catalog
CREATE TABLE designation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(100) NOT NULL UNIQUE,
    description TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 3. Seed standard academic designations
INSERT INTO designation (title, description) VALUES
('Professor', 'Senior academic faculty member'),
('Associate Professor', 'Mid-to-senior faculty member'),
('Assistant Professor', 'Faculty member leading academic courses'),
('Head of Department (HOD)', 'Academic department chairperson'),
('Dean / Director', 'Institutional dean or director'),
('Lab Instructor / Technical Assistant', 'Laboratory and technical instructional staff'),
('Faculty Club Advisor', 'Faculty coordinator for student societies and clubs'),
('Research Scholar / Fellow', 'Doctoral candidate or visiting researcher');
